-- ---------------------------------------------------------------- banks

create table if not exists banks (
  bank_id integer generated by default as identity primary key,
  bank_code varchar(30) not null unique,
  name varchar(200) not null,
  short_name varchar(50) not null,
  bank_type_id integer not null references master_bank_types(bank_type_id),
  active boolean not null default true,
  sponsored boolean not null default false,
  logo_url text,
  website_url varchar(500),
  email varchar(200),
  hotline varchar(50),
  phone varchar(50),
  whatsapp varchar(50),
  address varchar(500),
  branch_locator_url varchar(500),
  brand_color varchar(20),
  base_rate numeric(6,3) not null default 0,
  doc_charge_pct numeric(6,3) not null default 0,
  doc_charge_min numeric(14,2) not null default 0,
  doc_charge_cap numeric(14,2) not null default 0,
  rates_effective_date date,
  created_at timestamptz not null default now(),
  created_by varchar(100),
  updated_at timestamptz,
  updated_by varchar(100),
  is_deleted boolean not null default false
);
create index if not exists ix_banks_active on banks(active);

create table if not exists bank_allowed_sectors (
  bank_id integer not null references banks(bank_id) on delete cascade,
  sector_id integer not null references master_sectors(sector_id),
  primary key (bank_id, sector_id)
);

create table if not exists bank_max_terms_by_category (
  bank_id integer not null references banks(bank_id) on delete cascade,
  loan_category_id integer not null references master_loan_categories(loan_category_id),
  max_term_years integer not null,
  primary key (bank_id, loan_category_id)
);

create table if not exists bank_remarks (
  bank_remark_id integer generated by default as identity primary key,
  bank_id integer not null references banks(bank_id) on delete cascade,
  remark_text varchar(500) not null,
  sort_order integer not null default 0
