create table if not exists leads (
  lead_id integer generated by default as identity primary key,
  full_name varchar(200),
  phone varchar(30),
  email varchar(200),
  loan_category_id integer references master_loan_categories(loan_category_id),
  sector_id integer references master_sectors(sector_id),
  occupation_id integer references master_occupations(occupation_id),
  requested_amount numeric(14,2),
  net_monthly_salary numeric(14,2),
