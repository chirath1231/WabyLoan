  selected_product_id integer references loan_products(product_id),
  lead_status_id integer not null references master_lead_statuses(lead_status_id),
  notes text,
  source_page varchar(100),
  created_at timestamptz not null default now(),
  created_by varchar(100),
  updated_at timestamptz,
  updated_by varchar(100),
  is_deleted boolean not null default false,
  product_name varchar(200),
  rate_snapshot numeric(6,3),
  estimated_emi_snapshot numeric(14,2),
  requested_term_years integer,
  source_trigger varchar(50),
  assigned_to_user_id integer references users(user_id),
  consent_at timestamptz,
  consent_text_version varchar(20),
  verified_via varchar(20),
  user_id integer references users(user_id) on delete set null,
  applicant_snapshot jsonb not null default '{}'::jsonb
);
create index if not exists ix_leads_user_id on leads(user_id);
create index if not exists ix_leads_created_at on leads(created_at desc);
