-- Waby Loan schema (PostgreSQL)
--
-- A 1:1 relational port of the SQL Server database WabyLoanDB (see WabyLoanDB.sql at the repo root):
-- same 33 tables, same keys, same foreign-key graph, PascalCase names converted to snake_case.
--
-- Relationship map
--   Lookup ("master_*") tables       every coded value the UI/engine switches on (sector, category, status, ...)
--   banks                  1 ── n    loan_products, bank_remarks, company_lists
--   banks                  n ── n    master_sectors           via bank_allowed_sectors
--   banks                  n ── n    master_loan_categories   via bank_max_terms_by_category (+ max_term_years)
--   company_lists          1 ── n    company_entries
--   loan_products          n ── 1    company_lists (approved-employer list), 10 master_* lookups
--   loan_products          1 ── n    product_interest_rate_tiers, product_remarks
--   loan_products          n ── n    master_occupations       via product_target_occupations
--   loan_products          n ── 1    master_benchmark_rates (AWPLR a variable tier floats on)
--   master_sectors         1 ── 1    sector_dti_rates
--   master_sectors         n ── n    master_occupations       via sector_occupation_income_policies
--   leads                  n ── 1    banks, loan_products, master_sectors, master_occupations,
--                                    master_loan_categories, master_lead_statuses, users (assignee / submitter)
--   users                  n ── 1    master_roles;  audit_log n ── 1 users
--
-- Additions over the SQL Server original, needed by the React app's public accounts:
--   master_roles row 'user' (public applicant), users.full_name, leads.user_id + leads.applicant_snapshot.

