-- ---------------------------------------------------------------- products

create table if not exists loan_products (
  product_id integer generated by default as identity primary key,
  bank_id integer not null references banks(bank_id) on delete cascade,
  product_code varchar(50) not null,
  name varchar(200) not null,
  loan_category_id integer not null references master_loan_categories(loan_category_id),
  product_status_id integer not null references master_product_statuses(product_status_id),
  interest_rate_type_id integer not null references master_interest_rate_types(interest_rate_type_id),
  benchmark_rate_id integer references master_benchmark_rates(benchmark_rate_id),
  ot_included boolean not null default true,
  ot_pct numeric(5,2) not null default 100,
  ot_averaging_months integer,
  ot_types_allowed varchar(300),
  other_income_included boolean not null default true,
  other_income_pct numeric(5,2) not null default 0,
  other_income_types_allowed varchar(300),
  dti_override numeric(5,2),
  min_net_monthly_income numeric(14,2) not null default 0,
  eligible_sector_id integer references master_sectors(sector_id),
  age_min integer,
  age_max_at_maturity integer,
  min_employment_months integer not null default 0,
  max_term_years integer,
  repayment_period_min_years integer,
  repayment_period_max_years integer,
  companies_list_required boolean not null default false,
  companies_list_id integer references company_lists(list_id) on delete set null,
  loan_amount_min numeric(14,2) not null default 0,
  loan_amount_max numeric(14,2),
  doc_charge_basis_id integer not null references master_doc_charge_basis(doc_charge_basis_id),
  doc_charge_value numeric(10,2),
  doc_charge_min numeric(14,2),
  doc_charge_max numeric(14,2),
  balloon_allowed varchar(10) not null default 'na' check (balloon_allowed in ('na', 'no', 'yes')),
  balloon_pct numeric(5,2) not null default 0,
  guarantor_term_id integer not null references master_guarantor_terms(guarantor_term_id),
  collateral_type_id integer not null references master_collateral_types(collateral_type_id),
  insurance_type_id integer not null references master_insurance_types(insurance_type_id),
  early_settlement_allowed boolean not null default true,
  early_settlement_charge_pct numeric(5,2) not null default 0,
  late_payment_penalty_pct numeric(5,2) not null default 0,
  grace_period_days integer not null default 0,
  processing_days integer not null default 3,
  crib_check_required boolean not null default true,
  salary_credit_required boolean not null default false,
  co_applicant_allowed boolean not null default true,
  top_up_after_months integer,
  currency_id integer not null references master_currencies(currency_id),
  common_loan boolean not null default false,
  target_gender_id integer not null references master_genders(gender_id),
  created_at timestamptz not null default now(),
  created_by varchar(100),
  updated_at timestamptz,
  updated_by varchar(100),
  is_active boolean not null default true,
  is_deleted boolean not null default false,
  rates_effective_date date,
  constraint uq_loan_products_bank_code unique (bank_id, product_code)
);
create index if not exists ix_loan_products_bank_id on loan_products(bank_id);
create index if not exists ix_loan_products_category on loan_products(loan_category_id);
create index if not exists ix_loan_products_companies_list_id on loan_products(companies_list_id);

create table if not exists product_interest_rate_tiers (
  product_interest_rate_tier_id integer generated by default as identity primary key,
  product_id integer not null references loan_products(product_id) on delete cascade,
  rate_type_code varchar(30) not null,
  fixed_rate_value numeric(6,3),
  min_term_years integer not null,
  max_term_years integer not null,
  margin_over_awplr numeric(6,3),
  floor_rate numeric(6,3),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists ix_product_interest_rate_tiers_lookup
  on product_interest_rate_tiers(product_id, rate_type_code, min_term_years, max_term_years);

create table if not exists product_remarks (
  product_remark_id integer generated by default as identity primary key,
  product_id integer not null references loan_products(product_id) on delete cascade,
  remark_text varchar(500) not null,
  sort_order integer not null default 0
);

create table if not exists product_target_occupations (
  product_id integer not null references loan_products(product_id) on delete cascade,
  occupation_id integer not null references master_occupations(occupation_id),
  primary key (product_id, occupation_id)
);

