function getNested(obj, path) {
  return path.split('.').reduce((acc, part) => (acc && acc[part] !== undefined ? acc[part] : undefined), obj);
}

function interpolate(str, params) {
  if (!params) return str;
  return str.replace(/{{\s*(\w+)\s*}}/g, (_, key) => (params[key] !== undefined ? String(params[key]) : ''));
}

/** Looks up `key` (dot path, e.g. "step2.ageError") in the given language, falling back to English, then the raw key. */
export function translate(lang, key, params) {
  const dict = translations[lang] || translations.en;
  let value = getNested(dict, key);
  if (value === undefined) value = getNested(translations.en, key);
  if (value === undefined) return key;
  return interpolate(value, params);
}
